#!/usr/bin/env python3
"""Generates tests/timezone_cases.inc: expected local times of the time zones
around every DST transition (2025-2035), calculated with the IANA data of
python's zoneinfo. The test checks that TinyTimeZone (POSIX TZ string) gives
the same result. Usage: tests/gen_timezone_cases.py"""
import os
from datetime import datetime, timedelta, timezone
from zoneinfo import ZoneInfo

ZONES = ["Europe/Zurich", "Europe/London", "Europe/Moscow", "America/New_York",
         "America/Chicago", "America/Los_Angeles", "America/Phoenix",
         "America/St_Johns", "America/Sao_Paulo", "America/Santiago",
         "Pacific/Honolulu", "Asia/Tokyo", "Asia/Kolkata", "Asia/Kathmandu",
         "Asia/Tehran", "Africa/Johannesburg", "Australia/Sydney",
         "Australia/Adelaide", "Australia/Lord_Howe", "Pacific/Auckland",
         "Pacific/Chatham"]

def macro(iana):
    return "TZ_" + iana.replace("/", "_").replace("-", "_").upper()

start = datetime(2025, 1, 1, tzinfo=timezone.utc)
end = datetime(2036, 1, 1, tzinfo=timezone.utc)
rows = []
for name in ZONES:
    z = ZoneInfo(name)
    def info(t):
        l = t.astimezone(z)
        return l, (l.utcoffset(), bool(l.dst()))
    def row(t):
        l, (off, dst) = info(t)
        rows.append('    {%s, %d, "%s", %d, "%s"},  // %s' % (
            macro(name), int(t.timestamp()), l.strftime("%Y-%m-%d %H:%M:%S"),
            1 if dst else 0, l.tzname(), name))
    t = start
    prev = info(t)[1]
    step = timedelta(minutes=15)
    while t < end:
        cur = info(t)[1]
        if cur != prev:           # transition: the second before and the instant
            row(t - timedelta(seconds=1)); row(t)
            prev = cur
        t += step
    for year in (2025, 2026, 2030, 2035):  # samples in all seasons
        for month in range(1, 13):
            row(datetime(year, month, 15, 12, 0, tzinfo=timezone.utc))
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "timezone_cases.inc")
with open(out, "w") as f:
    f.write("// Generated by tests/gen_timezone_cases.py: do not edit.\n")
    f.write("// {time zone, UTC (s), local time, summer time, name}\n")
    f.write("\n".join(rows) + "\n")
print("wrote %d rows to %s" % (len(rows), out))

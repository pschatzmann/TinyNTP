#!/usr/bin/env python3
"""Generates src/TinyNTP/TinyTimeZones.h (the TZ_* defines for the library) and
src/TinyNTP/TinyTimeZoneTable.h (the same zones as a table, to look them up by
name with findTimeZone(); also used by the command line tool) from posix_tz_db
(MIT License).

Usage: tools/generate_timezones.py [zones.json | URL]
Default source: https://raw.githubusercontent.com/nayarsystems/posix_tz_db/master/zones.json
"""
import json
import os
import re
import sys
import urllib.request

URL = "https://raw.githubusercontent.com/nayarsystems/posix_tz_db/master/zones.json"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "TinyNTP", "TinyTimeZones.h")
OUT_LIB_TABLE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "TinyNTP", "TinyTimeZoneTable.h")

LIB_TABLE_HEADER = r"""/**
 * @file TinyTimeZoneTable.h
 * @brief Table of the IANA time zones and their POSIX TZ strings, to look up
 * a zone by its name at runtime (e.g. a name that the user selected):
 *
 *   const char* tz = findTimeZone("Europe/Zurich");
 *   if (tz != nullptr) ntp.setTimeZone(tz);
 *
 * Not included by TinyNTP.h: the table needs about 15 kB of flash. Use the
 * TZ_* defines of TinyTimeZones.h if the zone is known at compile time.
 *
 * This file is generated by tools/generate_timezones.py: do not edit.
 * Data: https://github.com/nayarsystems/posix_tz_db (MIT License)
 */

#pragma once
#include <cstddef>
#include <cstring>

namespace tiny_ntp {

/** @brief One time zone: IANA name and POSIX TZ string. */
struct TinyTimeZoneEntry {
  const char* name;  ///< IANA name, e.g. Europe/Zurich
  const char* tz;    ///< POSIX TZ string, e.g. CET-1CEST,M3.5.0,M10.5.0/3
};

/** @brief All zones, sorted by name. */
inline const TinyTimeZoneEntry tinyTimeZoneTable[] = {
"""

LIB_TABLE_FOOTER = r"""};

/** @brief Number of entries in tinyTimeZoneTable. */
constexpr size_t tinyTimeZoneCount = sizeof(tinyTimeZoneTable) / sizeof(tinyTimeZoneTable[0]);

/**
 * @brief The POSIX TZ string of an IANA time zone.
 * @param name IANA name, e.g. "Europe/Zurich" (case sensitive).
 * @return The TZ string or nullptr if the zone is not known.
 */
inline const char* findTimeZone(const char* name) {
  if (name == nullptr) return nullptr;
  // binary search: the table is sorted
  size_t lo = 0, hi = tinyTimeZoneCount;
  while (lo < hi) {
    const size_t mid = (lo + hi) / 2;
    const int cmp = strcmp(tinyTimeZoneTable[mid].name, name);
    if (cmp == 0) return tinyTimeZoneTable[mid].tz;
    if (cmp < 0) {
      lo = mid + 1;
    } else {
      hi = mid;
    }
  }
  return nullptr;
}

}  // namespace tiny_ntp
"""


def macro_name(iana):
    """Europe/Zurich -> TZ_EUROPE_ZURICH, Etc/GMT+5 -> TZ_ETC_GMT_PLUS_5"""
    name = iana.replace("+", "_PLUS_").replace("-", "_MINUS_" if iana.startswith("Etc/GMT") else "_")
    return "TZ_" + re.sub(r"[^A-Za-z0-9]+", "_", name).upper().strip("_")


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else URL
    if src.startswith("http"):
        with urllib.request.urlopen(src) as f:
            zones = json.load(f)
    else:
        with open(src) as f:
            zones = json.load(f)

    entries = {}
    for iana in sorted(zones):
        name = macro_name(iana)
        if name in entries:
            sys.exit("macro name collision: %s (%s)" % (name, iana))
        entries[name] = (iana, zones[iana])

    width = max(len(n) for n in entries)
    lines = [
        "/**",
        " * @file TinyTimeZones.h",
        " * @brief POSIX TZ strings for the IANA time zones, e.g. TZ_EUROPE_ZURICH.",
        " *",
        " * Usage: ntp.setTimeZone(TZ_EUROPE_ZURICH);",
        " *",
        " * The macro name is the IANA name in upper case, prefixed with TZ_ and with",
        " * all other characters replaced by '_' (America/New_York is",
        " * TZ_AMERICA_NEW_YORK). Unused defines do not use any memory.",
        " * A POSIX TZ string contains only the current rules of a time zone.",
        " *",
        " * This file is generated by tools/generate_timezones.py: do not edit.",
        " * Data: https://github.com/nayarsystems/posix_tz_db (MIT License)",
        " */",
        "",
        "#pragma once",
        "",
    ]
    for name, (iana, tz) in entries.items():
        lines.append('#define %s "%s"  // %s' % (name.ljust(width), tz, iana))
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %d zones to %s" % (len(entries), os.path.normpath(OUT)))

    # the table of the library: findTimeZone() (binary search: sorted by strcmp)
    body = "".join('    {"%s", "%s"},\n' % (iana, zones[iana]) for iana in sorted(zones))
    with open(OUT_LIB_TABLE, "w") as f:
        f.write(LIB_TABLE_HEADER + body + LIB_TABLE_FOOTER)
    print("wrote %d zones to %s" % (len(zones), os.path.normpath(OUT_LIB_TABLE)))


if __name__ == "__main__":
    main()
